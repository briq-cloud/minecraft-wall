const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const nodes = new Map();
const element = () => ({value:'10',disabled:false,textContent:'',dataset:{},children:[],append(...items){this.children.push(...items)},removeAttribute(name){delete this[name]},setAttribute(name,value){this[name]=value}});
const node = key => { if (!nodes.has(key)) nodes.set(key, element()); return nodes.get(key); };
node('#mode').value='cold';
let state = {workers:{},run:null,errors:[],summary:{vmRunning:0,preparing:0,running:0,finished:0,errors:0,started:0,costCents:0,elapsed:0},quota:{capacity:100,additionalCapacity:90,forkCapacity:80,canStart:false,fresh:true,budgetCents:0,creditBalanceCents:100,remainingTodayCents:0,spentTodayCents:100,ageSeconds:0}};
let pricing = {rates:[{currency:'usd',rate:1.2,asOf:'2026-11-06'}]};
const requests=[];
const context = vm.createContext({document:{querySelector:node,createElement:element},Date,AbortSignal,setTimeout:()=>{},fetch:async (url,options)=>{requests.push({url,options});return {ok:true,json:async()=>String(url).includes('/v1/pricing')?pricing:state}}});
const html = fs.readFileSync(path.join(__dirname,'controller.html'),'utf8');
assert.match(html,/Credits remaining today/);
assert.match(html,/for="count">Sandboxes/);
assert.doesNotMatch(html,/Independent demo worlds|euro cents|#d2ed9c/);
assert.match(html,/<svg[^>]+viewBox="0 0 28 28"/);
assert.match(html, /Minecraft Wall/);
assert.match(html, /href="https:\/\/github.com\/briq-cloud\/minecraft-wall"/);
assert.doesNotMatch(html, / · balance |Start fresh sandboxes|rateNote|USD rate as of|Metered · billed in EUR/);
assert.match(html, /class="button" href="https:\/\/github.com/);
assert.match(html, /Powered by briq/);
assert.match(html, /Cloud sandboxes for your agents/);
vm.runInContext(html.split('<script>')[1].split('</script>')[0],context);
(async()=>{
  assert.equal(node('main').dataset.size,'m','medium is the default');
  vm.runInContext("document.querySelector('#size-s').onclick()",context);
  assert.equal(node('main').dataset.size,'s');
  assert.equal(node('#size-s')['aria-pressed'],'true');
  assert.equal(node('#size-m')['aria-pressed'],'false');
  vm.runInContext("document.querySelector('#size-l').onclick()",context);
  assert.equal(node('main').dataset.size,'l');
  vm.runInContext("screenSize('invalid')",context);
  assert.equal(node('main').dataset.size,'m');
  await vm.runInContext('refresh()',context);
  assert.equal(node('#start').disabled,true,'zero budget disables launch');
  assert.equal(node('#stop').disabled,false,'stop remains available at zero');
  assert.equal(node('#credits').textContent,'€0.00');
  state.quota = {...state.quota,budgetCents:25,remainingTodayCents:25,canStart:true};
  await vm.runInContext('refresh()',context);
  assert.equal(node('#start').disabled,false,'fresh positive budget allows launch');
  assert.equal(node('#credits').textContent,'€0.25');
  assert.equal(vm.runInContext('money(0.3591)',context),'€0.0036','small usage retains useful precision');
  await vm.runInContext('loadRates()',context);
  node('#currency').value='usd';
  vm.runInContext("document.querySelector('#currency').onchange()",context);
  assert.equal(node('#credits').textContent,'$0.30','USD uses the API rate');
  assert.equal(node('#creditDetail').textContent,'Spent $1.20 / $1.50 daily');
  state.run={requested:10,workers:[],finishedAt:null,cancelled:false};
  state.summary={...state.summary,vmRunning:8,preparing:7,running:3};
  await vm.runInContext('refresh()',context);
  assert.equal(node('#running').textContent,8);
  assert.equal(node('#preparing').textContent,7);
  assert.equal(node('#playing').textContent,3);
  assert.equal(node('#start').textContent,'Add to fleet');
  assert.equal(node('#start').disabled,false,'active fleet accepts additions');
  assert.equal(node('#count').max,'90');
  node('#mode').value='fork';
  vm.runInContext('selection()',context);
  assert.equal(node('#count').max,'80','fork selection uses fresh disk headroom');
  await vm.runInContext("document.querySelector('#start').onclick()",context);
  const addition=requests.findLast(r=>r.url==='/api/start');
  assert.deepEqual(JSON.parse(addition.options.body),{count:Number(node('#count').value),mode:'fork',add:true});
  state.run.cancelled=true;
  await vm.runInContext('refresh()',context);
  assert.equal(node('#start').disabled,true,'cannot add to stopping fleet');
  state.run=null;node('#mode').value='cold';
  vm.runInContext("tile({id:'test',phase:'running',vmState:'running'})",context);
  assert.equal(vm.runInContext("tiles.get('test').img.hidden",context),false);
  vm.runInContext("tile({id:'test',phase:'stopped',vmState:'stopped'})",context);
  assert.equal(vm.runInContext("tiles.get('test').img.hidden",context),true);
  assert.equal(vm.runInContext("tiles.get('test').img.src",context),undefined,'stopped tile drops stale screen');
  assert.equal(vm.runInContext("tiles.get('test').message.textContent",context),'Stopped');
  assert.equal(vm.runInContext("tiles.get('test').icon.textContent",context),'■');
  vm.runInContext("tile({id:'test',phase:'stopped',vmState:'destroyed'})",context);
  assert.equal(vm.runInContext("tiles.get('test').message.textContent",context),'Sandbox removed');
  state.quota = {...state.quota,capacity:7};
  await vm.runInContext('refresh()',context);
  assert.equal(node('#count').max,'7');
  assert.equal(node('#count').value,'7','selection clamps when capacity drops');
  state.quota = {...state.quota,capacity:0};
  await vm.runInContext('refresh()',context);
  assert.equal(node('#count').disabled,true);
  assert.equal(node('#countValue').textContent,'0');
  assert.equal(node('#start').disabled,true);
  pricing = {rates:[]};
  vm.runInContext('usdRate=null',context);
  await vm.runInContext('loadRates()',context);
  assert.equal(node('#usd').disabled,true,'USD unavailable without a rate');
  assert.equal(node('#credits').textContent,'€0.25','missing rate falls back to EUR');
  state.quota = {...state.quota,fresh:false,canStart:false};
  await vm.runInContext('refresh()',context);
  assert.equal(node('#start').disabled,true,'stale quota disables launch');
  assert.equal(node('#credits').textContent,'Unknown');
  assert.equal(node('#stop').disabled,false,'stop remains available with stale quota');
  console.log('Controller UI budget checks passed');
})().catch(error=>{console.error(error);process.exitCode=1});
